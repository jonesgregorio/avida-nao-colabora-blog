## Cuidar de si não precisa exigir mais do que você tem

Em dias de pouca energia, até atividades básicas podem parecer grandes demais. Nessa hora, listas ambiciosas de autocuidado podem aumentar a culpa: você vê tudo o que “deveria” fazer e sente que falhou antes de começar. Uma alternativa é trocar a pergunta “como vou me recuperar?” por “qual é o menor cuidado que torna este momento um pouco menos difícil?”.

## Separe o essencial do ideal

O ideal talvez seja cozinhar algo completo, arrumar a casa e cumprir todos os compromissos. O essencial pode ser beber água, comer algo disponível, tomar um banho breve, trocar de roupa, responder apenas ao que é urgente ou pedir ajuda para uma tarefa. O essencial não é pouco quando é o que cabe.

Faça uma lista de três níveis:

- **mínimo:** o que protege o básico hoje;
- **se der:** uma ação que pode trazer um pouco de conforto;
- **não hoje:** tudo que pode esperar sem culpa.

## Reduza o atrito

Quando a energia está baixa, cada decisão pesa. Deixe uma opção fácil mais perto: uma garrafa de água, uma refeição simples, roupa confortável, uma mensagem pronta para avisar que você responderá depois. Preparar o ambiente não é falta de disciplina; é reconhecer que o contexto influencia o que conseguimos fazer.

## Peça apoio de forma específica

“Estou sem energia” pode ser difícil de traduzir para quem está ao redor. Tente pedir algo claro: “você consegue buscar isso?”, “pode ficar comigo enquanto resolvo esta ligação?”, “preciso remarcar hoje”. Pedidos específicos aumentam a chance de receber uma ajuda real.

## Não transforme descanso em prova

Descansar não precisa render uma versão nova de você. Às vezes, o resultado do descanso é apenas atravessar o dia com menos esforço. Isso já importa.

Se a baixa energia é frequente, intensa ou vem acompanhada de sofrimento que preocupa você, converse com um profissional habilitado. Em risco imediato, procure atendimento de emergência. Este conteúdo é educativo e não substitui cuidado profissional.

